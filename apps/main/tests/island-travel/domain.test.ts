test("paid reschedule preserves original ticket until success, then switches inventory and ledger once", () => {
  const original = changeOrder(createOrder([], trip, 2, "paid", true, today), "DJ-0001", "success");
  const target = searchTrips(conditions, today, original).find(t => t.depart === "13:30")!;
  const quote = quoteReschedule(original, "DJ-0001", target, today);
  assert.equal(quote.deltaCents, 2000);
  const pending = startPaidReschedule(original, quote, true, today);
  assert.equal(startPaidReschedule(pending, quote, true, today), pending);
  assert.equal(pending[0].trip.id, trip.id);
  assert.throws(() => quoteRefund(pending[0]));
  assert.throws(() => advanceJourney(pending, "DJ-0001", "boarding"));
  assert.throws(() => quoteReschedule(pending, "DJ-0001", target, today));
  assert.equal(invoiceUnavailableReason(pending[0]), "改签处理中，完成后再申请演示开票。");
  assert.throws(() => issueInvoice(pending, "DJ-0001", "personal", true));
  const unknown = resolvePaidReschedule(pending, "DJ-0001", "unknown", today).orders;
  assert.throws(() => resolvePaidReschedule(unknown, "DJ-0001", "cancel", today));
  assert.throws(() => resolvePaidReschedule(unknown, "DJ-0001", "success", today));
  const recovered = resolvePaidReschedule(unknown, "DJ-0001", "query", today);
  assert.equal(recovered.outcome, "completed");
  assert.equal(recovered.orders[0].trip.id, target.id);
  assert.equal(recovered.orders[0].amount, 276);
  assert.equal(recovered.orders[0].events.filter(e => e.type === "reschedule").length, 1);
  assert.deepEqual(paymentLedger(recovered.orders[0]), { paidCents: 27600, returnedCents: 0, netCents: 27600 });
  assert.equal(searchTrips(conditions, today, recovered.orders).find(t => t.id === trip.id)?.seats, trip.seats);
  assert.equal(searchTrips(conditions, today, recovered.orders).find(t => t.id === target.id)?.seats, target.seats - 2);
  assert.equal(resolvePaidReschedule(recovered.orders, "DJ-0001", "query", today).orders, recovered.orders);
});
test("payment failure, cancel and target shortage never partially change a ticket", () => {
  const original = changeOrder(createOrder([], trip, 1, "original", true, today), "DJ-0001", "success");
  const target = searchTrips(conditions, today, original).find(t => t.depart === "09:15")!;
  const quote = quoteReschedule(original, "DJ-0001", target, today);
  const pending = startPaidReschedule(original, quote, true, today);
  const failed = resolvePaidReschedule(pending, "DJ-0001", "failed", today);
  assert.equal(failed.outcome, "payment_failed");
  assert.equal(failed.orders[0].trip.id, trip.id);
  const cancelled = resolvePaidReschedule(failed.orders, "DJ-0001", "cancel", today).orders;
  assert.equal(cancelled[0].trip.id, trip.id);
  assert.equal(cancelled[0].reschedule, null);
  const competing = createOrder(pending, target, 3, "competing", true, today);
  assert.throws(() => resolvePaidReschedule(competing, "DJ-0001", "success", today));
  const unknown = resolvePaidReschedule(competing, "DJ-0001", "unknown", today).orders;
  const lookedUp = resolvePaidReschedule(unknown, "DJ-0001", "query", today);
  assert.equal(lookedUp.outcome, "inventory_unavailable");
  assert.equal(lookedUp.orders[0].trip.id, trip.id);
  assert.equal(lookedUp.orders[0].reschedule, null);
  assert.equal(lookedUp.orders[1].trip.id, target.id);
});
test("refund, no-price reschedule and stale quote use current fare and seats", () => {
  const expensive = searchTrips(conditions, today).find(t => t.depart === "16:00")!;
  const original = changeOrder(createOrder([], expensive, 1, "expensive", true, today), "DJ-0001", "success");
  const cheaper = searchTrips(conditions, today, original).find(t => t.depart === "07:30")!;
  const refundDifference = quoteReschedule(original, "DJ-0001", cheaper, today);
  assert.equal(refundDifference.deltaCents, -2000);
  assert.equal(submitSimpleReschedule(original, refundDifference, "failed", true, today), original);
  const changed = submitSimpleReschedule(original, refundDifference, "success", true, today);
  assert.equal(submitSimpleReschedule(changed, refundDifference, "success", true, today), changed);
  assert.equal(changed[0].trip.id, cheaper.id);
  assert.deepEqual(paymentLedger(changed[0]), { paidCents: 14800, returnedCents: 2000, netCents: 12800 });
  const samePrice = searchTrips(conditions, today, changed).find(t => t.depart === "13:30")!;
  const raised = quoteReschedule(changed, "DJ-0001", samePrice, today);
  assert.equal(submitSimpleReschedule(changed, refundDifference, "success", true, today), changed);
  assert.throws(() => quoteReschedule(changed, "DJ-0001", cheaper, today));
  assert.equal(raised.deltaCents, 1000);
  const versionChanged = issueInvoice(changed, "DJ-0001", "personal", true);
  assert.throws(() => startPaidReschedule(versionChanged, raised, true, today));
  const refund = quoteRefund(changed[0]);
  assert.equal(refund.amountCents, 12800);
  const refunded = submitRefund(changed, refund, "success", true);
  assert.deepEqual(paymentLedger(refunded[0]), { paidCents: 14800, returnedCents: 13520, netCents: 1280 });
  assert.equal(searchTrips(conditions, today, refunded).find(t => t.id === cheaper.id)?.seats, cheaper.seats);
});
test("zero difference and invoice records are scoped to fare version and order", () => {
  const first = searchTrips(conditions, today).find(t => t.depart === "09:15")!;
  const second = searchTrips(conditions, today).find(t => t.depart === "13:30")!;
  const original = changeOrder(createOrder([], first, 1, "invoice", true, today), "DJ-0001", "success");
  const issued = issueInvoice(original, "DJ-0001", "personal", true);
  assert.equal(activeInvoice(issued[0])?.type, "invoice");
  assert.equal(issueInvoice(issued, "DJ-0001", "personal", true), issued);
  assert.throws(() => issueInvoice(issued, "DJ-0001", "company", true));
  const quote = quoteReschedule(issued, "DJ-0001", second, today);
  assert.equal(quote.deltaCents, 0);
  const changed = submitSimpleReschedule(issued, quote, "success", true, today);
  assert.equal(activeInvoice(changed[0]), null);
  const reissued = issueInvoice(changed, "DJ-0001", "company", true);
  assert.equal(activeInvoice(reissued[0])?.type, "invoice");
  assert.equal(reissued[0].events.filter(e => e.type === "invoice").length, 2);
  const refund = submitRefund(reissued, quoteRefund(reissued[0]), "success", true);
  assert.equal(activeInvoice(refund[0]), null);
  assert.throws(() => issueInvoice(refund, "DJ-0001", "personal", true));
  const another = changeOrder(createOrder(reissued, trip, 1, "other", true, today), "DJ-0002", "success");
  assert.equal(activeInvoice(another[1]), null);
  assert.equal(activeInvoice(another[0])?.type, "invoice");
});
