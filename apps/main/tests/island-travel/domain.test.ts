test("refund quote is bound to order version and releases inventory only once", () => {
  const scarce = searchTrips(conditions, today)[1];
  const pending = createOrder([], scarce, 3, "refund", true, today);
  const ticketed = changeOrder(pending, pending[0].id, "success");
  const quote = quoteRefund(ticketed[0]);
  assert.equal(quote.amountCents, ticketed[0].amount * 100);
  assert.equal(quote.feeCents, Math.round(quote.amountCents / 10));
  assert.equal(quote.refundCents, quote.amountCents - quote.feeCents);
  assert.throws(() => submitRefund(ticketed, quote, "success", false));
  assert.equal(submitRefund(ticketed, quote, "failed", true), ticketed);
  assert.throws(() => submitRefund(ticketed, { ...quote, feeCents: 0 }, "success", true));
  const boarding = advanceJourney(ticketed, ticketed[0].id, "boarding");
  assert.throws(() => submitRefund(boarding, quote, "success", true));
  const refunded = submitRefund(ticketed, quote, "success", true);
  assert.equal(refunded[0].status, "refunded");
  assert.equal(submitRefund(refunded, quote, "success", true), refunded);
  assert.equal(searchTrips(conditions, today, refunded)[1].seats, scarce.seats);
  const repurchased = createOrder(refunded, scarce, 3, "repurchase", true, today);
  assert.equal(repurchased[1].id, "DJ-0002");
  assert.throws(() => createOrder(repurchased, scarce, 1, "excess", true, today));
});
